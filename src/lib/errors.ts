/**
 * BLOQUE: Errores de aplicación (sustituye ApiError de lib/appwrite).
 */

export class ApiError extends Error {
  readonly code: string;
  readonly status?: number;

  constructor(code: string, message: string, status?: number) {
    super(message);
    this.name = 'ApiError';
    this.code = code;
    this.status = status;
  }
}
