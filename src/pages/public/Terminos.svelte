<article class="legal card glass-panel">
  <section>
    <h2>1. Qué es Huella</h2>
    <p>
      <strong>Huella</strong> es una plataforma digital de <strong>averiguación y gestión de
      solicitudes</strong> orientada a familiares que buscan información sobre personas vinculadas a
      contextos de conflicto en el exterior (en particular, situaciones que han afectado a ciudadanos
      cubanos). El servicio principal es la <strong>investigación y el seguimiento documental</strong>
      del caso; de forma complementaria, cuando corresponda, se podrá orientar sobre la posibilidad de
      gestionar la <strong>prima o compensación</strong> a la que la familia pudiera tener derecho si se
      confirma un fallecimiento.
    </p>
    <p>
      Huella <strong>no es un banco, una aseguradora ni un intermediario de pagos en línea</strong>.
      Los pagos de primas, si aplican, <strong>no se procesan dentro de esta aplicación</strong>.
    </p>
  </section>

  <section>
    <h2>2. Naturaleza del servicio</h2>
    <ul>
      <li>
        Registras una <strong>solicitud de averiguación</strong> sobre un familiar o persona de interés.
      </li>
      <li>
        Un operador revisa el expediente y puede solicitar <strong>verificación de identidad</strong>
        (digital o asistida) antes de avanzar.
      </li>
      <li>
        El estado del expediente puede consultarse con un <strong>código de seguimiento</strong>, sin
        necesidad de crear una cuenta de usuario.
      </li>
      <li>
        El resultado de la averiguación <strong>puede o no incluir confirmación de fallecimiento</strong>.
        La plataforma no garantiza un resultado concreto ni plazos fijos.
      </li>
      <li>
        La orientación sobre prima o compensación es <strong>secundaria y condicionada</strong> a que el
        caso lo permita; no constituye promesa de cobro ni de montos.
      </li>
    </ul>
  </section>

  <section>
    <h2>3. Lo que Huella no hace</h2>
    <ul>
      <li>No representa necesariamente a ninguna autoridad militar, gubernamental o judicial.</li>
      <li>No sustituye asesoría legal formal; la información del sitio es orientativa.</li>
      <li>No garantiza la localización de la persona, la entrega de restos ni el cobro de una prima.</li>
      <li>No almacena ni transfiere fondos de primas a través de esta web.</li>
      <li>No ofrece un servicio de mensajería o redes sociales entre usuarios.</li>
    </ul>
  </section>

  <section>
    <h2>4. Obligaciones del solicitante</h2>
    <ul>
      <li>Proporcionar datos <strong>veraces y actualizados</strong> en la medida de lo posible.</li>
      <li>
        Usar la plataforma solo si tienes un interés legítimo (familiar u otro vínculo justificado) sobre
        la persona indicada.
      </li>
      <li>
        Conservar el <strong>código de seguimiento</strong>; es la vía principal para consultar el
        expediente.
      </li>
      <li>
        Completar, cuando se solicite, la verificación de identidad de buena fe (Didit u otra vía asistida).
      </li>
      <li>No utilizar la plataforma para hostigar, suplantar o dañar a terceros.</li>
    </ul>
  </section>

  <section>
    <h2>5. Datos personales y confidencialidad</h2>
    <p>
      Tratamos los datos que nos envías (nombre, contacto, descripción del caso y, en su caso, datos de
      verificación) con la finalidad de <strong>gestionar el expediente</strong>, contactarte y cumplir
      obligaciones de seguridad (por ejemplo, KYC).
    </p>
    <p>
      Las <strong>notas internas</strong> del equipo no se muestran en el seguimiento público. El
      <strong>mensaje público</strong> del expediente sí puede ser visible para quien conozca el código.
    </p>
    <p>
      Quien conoce el código de seguimiento puede consultar el estado del caso; protégelo como información
      sensible.
    </p>
  </section>

  <section>
    <h2>6. Verificación de identidad</h2>
    <p>
      En etapas avanzadas del expediente puede requerirse verificación (proveedor digital o procedimiento
      asistido). Su objetivo es proteger a las familias y reducir fraudes. El rechazo o la imposibilidad de
      verificar puede limitar el avance del caso.
    </p>
  </section>

  <section>
    <h2>7. Estados del expediente</h2>
    <p>De forma orientativa, un expediente puede pasar por:</p>
    <ul>
      <li><strong>Pendiente</strong> — registrada, aún no atendida.</li>
      <li><strong>Atendido · no verificado</strong> — en manos del equipo; falta verificación.</li>
      <li><strong>Verificado</strong> — identidad confirmada; investigación en curso.</li>
      <li><strong>Cerrado</strong> — proceso completado de forma satisfactoria según el equipo.</li>
      <li><strong>Cancelada</strong> — el proceso no continúa (no equivale a un cierre exitoso).</li>
    </ul>
  </section>

  <section>
    <h2>8. Limitación de responsabilidad</h2>
    <p>
      En la medida permitida por la ley aplicable, Huella y su equipo no responden por daños indirectos,
      pérdida de oportunidad, expectativas de cobro no materializadas, ni por información incompleta o
      errónea suministrada por el solicitante o por fuentes externas de investigación.
    </p>
    <p>
      El servicio depende de la disponibilidad de información, de terceros y de condiciones operativas
      (incluyendo conectividad en distintos países).
    </p>
  </section>

  <section>
    <h2>9. Modificaciones</h2>
    <p>
      Podemos actualizar estos términos. La versión vigente se identifica por la fecha indicada al inicio
      de esta página. El uso continuado de la plataforma tras un cambio relevante implica la aceptación de
      la nueva versión para solicitudes posteriores.
    </p>
  </section>

  <section>
    <h2>10. Contacto</h2>
    <p>
      Para consultas sobre un expediente en curso, utiliza el canal que el equipo indique en el seguimiento
      o el correo de contacto publicado en la plataforma.
    </p>
  </section>

